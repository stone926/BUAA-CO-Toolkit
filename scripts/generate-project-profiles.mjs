// Generate the host-free profile identity registry from the course configuration.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'resources/co/courseConfig.json');
const target = path.join(root, 'src/generated/projectProfiles.ts');
const profiles = JSON.parse(fs.readFileSync(source, 'utf8')).profiles;
const ids = Object.keys(profiles);
if (ids.length === 0 || ids.some((id) => !/^P\d+$/.test(id))) {
  throw new Error('courseConfig.profiles must contain valid P-number profile ids');
}
const courseIds = ids.filter((id) => profiles[id].capabilities?.trace === true);
const verilogCpuIds = ids.filter((id) => profiles[id].capabilities?.asmNeededForVerilog === true);
if (courseIds.length === 0 || verilogCpuIds.length === 0) {
  throw new Error('courseConfig must define trace and Verilog CPU profile capabilities');
}
const isaPolicies = JSON.parse(fs.readFileSync(path.join(root, 'resources/mips/isa.json'), 'utf8')).profilePolicies;
if (JSON.stringify([...courseIds].sort()) !== JSON.stringify(Object.keys(isaPolicies).sort())) {
  throw new Error('courseConfig trace profiles and isa.json profilePolicies must have identical ids');
}
const content = [
  '// @generated by scripts/generate-project-profiles.mjs from resources/co/courseConfig.json — DO NOT EDIT.',
  '// @index profile-ids — host-free ProjectProfile identities for host, LSP and core clients',
  `export const concreteProjectProfiles = ${JSON.stringify(ids)} as const;`,
  `export const courseProfileIds = ${JSON.stringify(courseIds)} as const;`,
  `export const verilogCpuProfileIds = ${JSON.stringify(verilogCpuIds)} as const;`,
  "export type ConcreteProjectProfile = typeof concreteProjectProfiles[number];",
  "export type ProjectProfile = 'auto' | ConcreteProjectProfile;",
  'export type CourseProjectProfile = typeof courseProfileIds[number];',
  'export type VerilogCpuProfile = typeof verilogCpuProfileIds[number];',
  '',
  'const concreteProfileSet: ReadonlySet<string> = new Set(concreteProjectProfiles);',
  'const courseProfileSet: ReadonlySet<string> = new Set(courseProfileIds);',
  'const verilogCpuProfileSet: ReadonlySet<string> = new Set(verilogCpuProfileIds);',
  'export function isConcreteProjectProfile(value: unknown): value is ConcreteProjectProfile {',
  "  return typeof value === 'string' && concreteProfileSet.has(value);",
  '}',
  'export function isCourseProjectProfile(value: unknown): value is CourseProjectProfile {',
  "  return typeof value === 'string' && courseProfileSet.has(value);",
  '}',
  'export function isVerilogCpuProfile(value: unknown): value is VerilogCpuProfile {',
  "  return typeof value === 'string' && verilogCpuProfileSet.has(value);",
  '}',
  ''
].join('\n');
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : undefined;
if (process.argv.includes('--check')) {
  if (current !== content) {
    throw new Error(`${path.relative(root, target)} is stale; run node scripts/generate-project-profiles.mjs`);
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (current !== content) {
    fs.writeFileSync(target, content);
  }
}
